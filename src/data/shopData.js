// Helper functions
export function getProductsByCategory(categorySlug) {
  return shopProducts.filter((p) => p.categorySlug === categorySlug);
}

export function getBestSellers(limit = 6) {
  return shopProducts.filter((p) => p.isBestSeller).slice(0, limit);
}

export function getBrandedProducts(limit = 6) {
  return shopProducts.filter((p) => p.isBranded).slice(0, limit);
}

export function getCategoryBySlug(slug) {
  return shopCategories.find((c) => c.slug === slug);
}

export function getProductBySlug(slug) {
  return shopProducts.find((p) => p.slug === slug);
}

